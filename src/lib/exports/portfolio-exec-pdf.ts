// Page 3 — gate rail + project summary

function drawGateRail(
  doc: jsPDF,
  theme: ExportTheme,
  data: PortfolioExecReportData,
  top: number,
): number {
  const width = contentWidth(doc);
  const labelW = mm(48);
  const railLeft = PAGE.margin + labelW;
  const railW = width - labelW - mm(4);
  const rowH = mm(11);
  let y = top;

  // Phase headings
  doc.setFont("helvetica", "bold");
  doc.setFontSize(FONT.caption);
  doc.setTextColor(NEUTRAL.muted[0], NEUTRAL.muted[1], NEUTRAL.muted[2]);
  PHASE_RAIL.forEach((phase, i) => {
    doc.text(titleCase(phase === "cod" ? "COD" : phase), plotX(i, PHASE_RAIL.length, railLeft, railW), y, {
      align: "center",
    });
  });
  y += mm(5);

  const rows = data.gates.length ? data.gates : [];
  if (rows.length === 0) {
    resetInk(doc);
    return docCaption(doc, "No projects with recorded phase gates.", y + mm(2));
  }

  rows.forEach((row) => {
    const cy = y + rowH / 2;
    doc.setFont("helvetica", "bold");
    doc.setFontSize(FONT.caption);
    doc.setTextColor(NEUTRAL.ink[0], NEUTRAL.ink[1], NEUTRAL.ink[2]);
    doc.text(sanitize(row.project_code), PAGE.margin, cy - 2);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(NEUTRAL.muted[0], NEUTRAL.muted[1], NEUTRAL.muted[2]);
    doc.text(
      doc.splitTextToSize(sanitize(row.project_name), labelW - mm(4))[0] ?? "",
      PAGE.margin,
      cy + 6,
    );

    doc.setDrawColor(NEUTRAL.line[0], NEUTRAL.line[1], NEUTRAL.line[2]);
    doc.setLineWidth(1.2);
    doc.line(railLeft, cy, railLeft + railW, cy);

    const active = railIndex(row.phase);
    doc.setLineWidth(1.6);
    doc.setDrawColor(theme.primary[0], theme.primary[1], theme.primary[2]);
    if (active > 0) {
      doc.line(railLeft, cy, plotX(active, PHASE_RAIL.length, railLeft, railW), cy);
    }
    PHASE_RAIL.forEach((_, i) => {
      const x = plotX(i, PHASE_RAIL.length, railLeft, railW);
      const reached = i <= active;
      const color = reached ? theme.primary : NEUTRAL.line;
      doc.setFillColor(color[0], color[1], color[2]);
      doc.circle(x, cy, i === active ? 3.4 : 2.4, "F");
    });
    y += rowH;
  });
  resetInk(doc);
  return y + mm(2);
}

