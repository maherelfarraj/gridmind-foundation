function drawCover(doc: jsPDF, theme: ExportTheme, data: PortfolioExecReportData): void {
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();

  doc.setFillColor(theme.primary[0], theme.primary[1], theme.primary[2]);
  doc.rect(0, 0, pageW, mm(70), "F");
  doc.setFillColor(theme.accent[0], theme.accent[1], theme.accent[2]);
  doc.rect(0, mm(70), pageW, 2.4, "F");

  if (theme.logoDataUrl) {
    try {
      doc.addImage(
        theme.logoDataUrl,
        /^data:image\/jpe?g/.test(theme.logoDataUrl) ? "JPEG" : "PNG",
        PAGE.margin,
        mm(22),
        mm(45),
        mm(16),
        undefined,
        "FAST",
      );
    } catch {
      /* a broken logo must never break the document */
    }
  }

  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.text(sanitize(data.company.legalName ?? data.company.name), PAGE.margin, mm(52));

  doc.setTextColor(NEUTRAL.ink[0], NEUTRAL.ink[1], NEUTRAL.ink[2]);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(28);
  doc.text(DOC_TITLE, PAGE.margin, mm(100));

  doc.setFont("helvetica", "normal");
  doc.setFontSize(13);
  doc.setTextColor(NEUTRAL.muted[0], NEUTRAL.muted[1], NEUTRAL.muted[2]);
  doc.text(`Reporting period: ${periodLabel(data.period)}`, PAGE.margin, mm(112));

  const rows: Array<[string, string]> = [
    ["Company", sanitize(data.company.legalName ?? data.company.name)],
    ["Projects in scope", fmtNum(data.rowCounts.projects)],
    ["Base currency", sanitize(data.baseCurrency)],
    ["Generated by", sanitize(data.generatedBy)],
    ["Generated at", utcDateTime(data.generatedAt)],
  ];
  let y = mm(132);
  rows.forEach(([label, value]) => {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(FONT.caption);
    doc.setTextColor(NEUTRAL.muted[0], NEUTRAL.muted[1], NEUTRAL.muted[2]);
    doc.text(label.toUpperCase(), PAGE.margin, y);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(FONT.body);
    doc.setTextColor(NEUTRAL.body[0], NEUTRAL.body[1], NEUTRAL.body[2]);
    doc.text(value, PAGE.margin + mm(45), y);
    y += mm(8);
  });

  const soft = tint(theme.primary, 0.9);
  doc.setFillColor(soft[0], soft[1], soft[2]);
  doc.rect(0, pageH - mm(46), pageW, mm(28), "F");
  doc.setFillColor(theme.accent[0], theme.accent[1], theme.accent[2]);
  doc.rect(0, pageH - mm(46), pageW, 1.2, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(FONT.caption);
  doc.setTextColor(theme.primary[0], theme.primary[1], theme.primary[2]);
  doc.text(LIVE_DATA_STAMP.toUpperCase(), PAGE.margin, pageH - mm(37));
  doc.setFont("helvetica", "normal");
  doc.setTextColor(NEUTRAL.muted[0], NEUTRAL.muted[1], NEUTRAL.muted[2]);
  doc.text(CONFIDENTIALITY_NOTE, PAGE.margin, pageH - mm(30));
  doc.text(LANGUAGE_NOTE, PAGE.margin, pageH - mm(24));
  resetInk(doc);
}

