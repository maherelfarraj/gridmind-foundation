// Entry point

export interface ExecReportPdf {
  bytes: Uint8Array;
  filename: string;
}

/**
 * Pure generator: PortfolioExecReportData → PDF bytes. Safe to call from a
 * browser click handler or, later, from the scheduled-reports runner.
 */
export async function buildPortfolioExecReportPdf(
  data: PortfolioExecReportData,
): Promise<ExecReportPdf> {
  const theme = await createExportTheme(
    {
      primaryColor: data.branding.primaryColor,
      accentColor: data.branding.accentColor,
      footerText: data.branding.footerText,
      logoSignedUrl: data.branding.logoSignedUrl,
    },
    { name: data.company.name, legal_name: data.company.legalName },
  );

  const doc = createDoc();
  drawCover(doc, theme, data);
  doc.addPage();
  drawKpiPage(doc, theme, data);
  drawCashPage(doc, theme, data);
  drawProjectsPage(doc, theme, data);
  drawExposurePage(doc, theme, data);
  drawExecFooters(doc, theme, data);

  const buf = doc.output("arraybuffer");
  return {
    bytes: new Uint8Array(buf),
    filename: execReportFilename(data.company.name, data.period),
  };
}
