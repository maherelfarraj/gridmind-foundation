function drawExposurePage(doc: jsPDF, theme: ExportTheme, data: PortfolioExecReportData): void {
  const subtitle = periodLabel(data.period);
  const ex = data.exposure;
  doc.addPage();
  let y = drawHeaderBand(doc, theme, DOC_TITLE, subtitle);
  y = docH1(doc, "HSE and quality exposure", y);

  const trend = trirTrend(ex.trir_current, ex.trir_prior);
  const arrow = trend.direction === "down" ? "v" : trend.direction === "up" ? "^" : "-";
  y = drawBigNumbers(
    doc,
    theme,
    [
      { label: "Open incidents", value: fmtNum(ex.incidents_open) },
      {
        label: "TRIR (12 months)",
        value: ex.trir_current === null ? "—" : Number(ex.trir_current).toFixed(2),
        hint:
          trend.direction === "unknown"
            ? "No comparable prior period"
            : `${arrow} vs prior ${ex.trir_prior === null ? "—" : Number(ex.trir_prior).toFixed(2)}`,
      },
      { label: "Open punch items", value: fmtNum(totalCounts(ex.punch_open)) },
      { label: "Open hold points", value: fmtNum(ex.hold_points_open) },
    ],
    y,
    { perRow: 4 },
  );

  y = docH2(doc, theme, "Open incidents by severity", y + mm(6));
  y = docTable(doc, theme, {
    startY: y,
    pageHeader: { title: DOC_TITLE, subtitle },
    head: [["Severity", "Open"]],
    body: orderedCounts(ex.incidents_by_severity, SEVERITY_ORDER).map((r) => [
      titleCase(r.key),
      fmtNum(r.count),
    ]),
    columnStyles: { 1: numericCol },
  });

  y = docH2(doc, theme, "Open quality exposure", y + mm(6));
  const ncr = Object.entries(ex.ncr_open_by_status ?? {}).sort((a, b) => a[0].localeCompare(b[0]));
  y = docTable(doc, theme, {
    startY: y,
    pageHeader: { title: DOC_TITLE, subtitle },
    head: [["Category", "Open"]],
    body: [
      ...orderedCounts(ex.punch_open, PUNCH_ORDER).map((r) => [
        `Punch ${r.key}${r.key === "A" ? " (gate-blocking)" : ""}`,
        fmtNum(r.count),
      ]),
      ...(ncr.length
        ? ncr.map(([status, n]) => [`NCR — ${titleCase(status)}`, fmtNum(n)])
        : [["NCR — none open", "0"]]),
      ["ITP hold points open", fmtNum(ex.hold_points_open)],
    ],
    columnStyles: { 1: numericCol },
  });

  y = docH2(doc, theme, "Project exposure heat table", y + mm(6));
  const heat = sortByExposure(ex.by_project);
  const maxima = EXPOSURE_DIMENSIONS.map((dim) =>
    Math.max(0, ...heat.map((r) => Number(r[dim] ?? 0))),
  );
  docTable(doc, theme, {
    startY: y,
    pageHeader: { title: DOC_TITLE, subtitle },
    head: [["Project", "Incidents", "Punch A", "Punch B", "NCRs", "Hold points", "Days since"]],
    body: heat.length
      ? heat.map((r) => [
          `${sanitize(r.project_code)}\n${sanitize(r.project_name)}`,
          fmtNum(r.incidents_open),
          fmtNum(r.punch_a_open),
          fmtNum(r.punch_b_open),
          fmtNum(r.ncr_open),
          fmtNum(r.hold_points_open),
          r.days_since_last_incident === null ? "—" : fmtNum(r.days_since_last_incident),
        ])
      : [["No projects in scope", "—", "—", "—", "—", "—", "—"]],
    styles: { fontSize: 7.8 },
    columnStyles: {
      1: numericCol,
      2: numericCol,
      3: numericCol,
      4: numericCol,
      5: numericCol,
      6: numericCol,
    },
    didParseCell: (cell) => {
      if (cell.section !== "body" || cell.column.index === 0 || cell.column.index > 5) return;
      const row = heat[cell.row.index];
      if (!row) return;
      const dim = EXPOSURE_DIMENSIONS[cell.column.index - 1];
      const value = Number(row[dim] ?? 0);
      const max = maxima[cell.column.index - 1] || 0;
      if (value <= 0) return;
      const share = max > 0 ? value / max : 1;
      cell.cell.styles.fillColor = tint([190, 45, 45], 1 - Math.min(1, 0.25 + share * 0.55)) as Rgb;
      cell.cell.styles.fontStyle = "bold";
      cell.cell.styles.halign = "right";
    },
  });
}

// ---------------------------------------------------------------------------
// Footers (page numbers + confidentiality + live-data stamp + language note)

function drawExecFooters(doc: jsPDF, theme: ExportTheme, data: PortfolioExecReportData): void {
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const total = doc.getNumberOfPages();
  for (let i = 1; i <= total; i++) {
    doc.setPage(i);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(FONT.footer - 0.5);
    doc.setTextColor(NEUTRAL.muted[0], NEUTRAL.muted[1], NEUTRAL.muted[2]);
    doc.setDrawColor(NEUTRAL.line[0], NEUTRAL.line[1], NEUTRAL.line[2]);
    doc.setLineWidth(0.5);
    doc.line(PAGE.margin, pageH - mm(16), pageW - PAGE.margin, pageH - mm(16));
    doc.text(
      `${CONFIDENTIALITY_NOTE} ${LANGUAGE_NOTE}`,
      PAGE.margin,
      pageH - mm(12),
    );
    doc.text(
      `${theme.footerLeft || sanitize(data.company.name)} · ${LIVE_DATA_STAMP} ${utcDateTime(
        data.generatedAt,
      )}`,
      PAGE.margin,
      pageH - mm(8),
    );
    doc.text(`Page ${i} of ${total}`, pageW - PAGE.margin, pageH - mm(8), { align: "right" });
  }
  resetInk(doc);
}

